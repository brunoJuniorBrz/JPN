import { expect,test } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { openResultTab } from "./result-tabs";

for(const width of [390,1440])test(`projeto declarado salvo -> solver real -> recuperação e invalidação em ${width}px`,async({page})=>{
  test.setTimeout(120000);await page.setViewportSize({width,height:950});
  const errors:string[]=[];page.on("pageerror",e=>errors.push(e.message));
  const physical=JSON.parse(await readFile("src/domain/test-support/m34ab-declared.json","utf8"));physical.name=`Obra declarada do usuário ${width}`;physical.client="Cliente de integração";
  await page.goto("/projetos/novo");await page.getByText("Importar modelo estrutural declarado",{exact:true}).click();
  await page.getByLabel("Importar modelo estrutural JSON").setInputFiles({name:"minha-estrutura.json",mimeType:"application/json",buffer:Buffer.from(JSON.stringify(physical))});
  await expect(page).toHaveURL(/\/projetos\/[a-f0-9-]+\?fluxo=levantamento/);const savedURL=page.url();
  const ownerId=new URL(savedURL).pathname.split("/").at(-1)!;expect(ownerId).not.toBe(physical.id);
  await expect(page.getByRole("heading",{name:physical.name,exact:true})).toBeVisible();
  const view=page.getByTestId("declared-line-view").filter({visible:true});await expect(view).toBeVisible();
  await expect(view.locator("[data-node-id]")).toHaveCount(4);await expect(view.locator("[data-piece-id]")).toHaveCount(3);
  await expect(view.locator('[data-node-id="B2"]')).toHaveAttribute("data-x-mm","2000");
  await page.reload();await expect(page.getByRole("heading",{name:physical.name,exact:true})).toBeVisible();
  await openResultTab(page,"Engenharia");const panel=page.getByTestId("mixed-workspace");
  await expect(panel.getByTestId("mixed-scope")).toContainText("OBRA ATUAL");
  await expect(panel.getByTestId("mixed-health")).toContainText("PyNiteFEA 3.2.1",{timeout:25000});
  const response=page.waitForResponse(r=>r.url().endsWith("/api/experimental/mixed3d")&&r.request().method()==="POST");
  await panel.getByRole("button",{name:"Executar análise mista local",exact:true}).click();
  const r=await response;expect(r.status()).toBe(200);const payload=r.request().postDataJSON(),out=await r.json();
  expect(payload.project.id).toBe(ownerId);expect(payload.nodes.find((n:{id:string})=>n.id==="B2").x_m).toBe(2);
  expect(out.result.combinations.Q1.nodes.B2.translation_m[2]).toBeCloseTo(-.0125,10);
  await expect(panel.getByTestId("mixed-result-state")).toContainText("Resultado calculado");
  await expect(panel.locator('[data-piece-id="AX1"] > line').first()).toHaveAttribute("stroke","#27858f");
  const downloadEvent=page.waitForEvent("download");await panel.getByRole("button",{name:"Exportar resultados mistos",exact:true}).click();const download=await downloadEvent;
  const exported=await readFile((await download.path())!,"utf8");
  // Switching the parent result tabs must preserve the completed calculation.
  await openResultTab(page,"Modelo 3D");await openResultTab(page,"Engenharia");await expect(panel.getByTestId("mixed-result-state")).toContainText("Resultado calculado");
  await page.reload();await openResultTab(page,"Engenharia");await panel.getByText("Recuperar resultado exportado",{exact:true}).click();
  await panel.getByLabel("Restaurar resultado misto JSON").setInputFiles({name:"resultado.json",mimeType:"application/json",buffer:Buffer.from(exported)});
  await expect(panel.getByTestId("mixed-result-state")).toContainText("Resultado restaurado");
  await panel.getByRole("button",{name:"Preparação mista",exact:true}).click();
  await panel.getByLabel("Seção física cadastrada",{exact:true}).selectOption("S1");
  await panel.getByLabel("Seção S1 · Inércia Iy (cm⁴)",{exact:true}).fill("200");
  await panel.getByLabel("Seção S1 · revisão",{exact:true}).fill("2");
  await expect(panel.getByTestId("mixed-stale")).toBeVisible();
  await panel.getByLabel("Restaurar resultado misto JSON").setInputFiles({name:"obsoleto.json",mimeType:"application/json",buffer:Buffer.from(exported)});
  await expect(panel.getByRole("alert").filter({hasText:"Resultado não restaurado"})).toBeVisible();
  await expect(panel.getByRole("button",{name:"Executar análise mista local",exact:true})).toBeEnabled({timeout:25000});
  const nextResponse=page.waitForResponse(r=>r.url().endsWith("/api/experimental/mixed3d")&&r.request().method()==="POST");
  await panel.getByRole("button",{name:"Executar análise mista local",exact:true}).click();const recalculated=await(await nextResponse).json();
  expect(recalculated.result.input_sha256).not.toBe(out.result.input_sha256);
  expect(recalculated.result.combinations.Q1.nodes.B2.translation_m[2]).toBeCloseTo(-.006666666666666667,10);
  await expect(panel.getByTestId("mixed-result-state")).toContainText("Resultado calculado");
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:`validation/integration/declared-${width}.png`,fullPage:true});expect(errors).toEqual([]);
});
