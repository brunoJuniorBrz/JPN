import {expect,test} from "@playwright/test";

for (const width of [375,1440]) test(`modo acabado preserva a estrutura, personaliza telhado e exporta PNG em ${width}px`, async ({page})=>{
  await page.setViewportSize({width,height:900});
  const errors:string[]=[];page.on("pageerror",e=>errors.push(e.message));
  await page.goto("/projetos/novo");
  await page.getByLabel("Largura (m)").fill("10");
  await page.getByLabel("Comprimento (m)").fill("20");
  await page.getByLabel("Altura (m)").fill("4");
  await page.getByRole("button",{name:"Gerar modelo 3D"}).click();
  const canvas=page.getByRole("img",{name:"Modelo 3D da estrutura"});
  await expect(canvas).toHaveAttribute("data-mode","profiles");
  const before=await page.getByTestId("takeoff-totals").innerText();
  const previous=await page.evaluate(()=>JSON.stringify(JSON.parse(localStorage.getItem("jpn-projetos:v1")!).projects.at(-1).planning));
  await page.getByRole("group",{name:"Modo de visualização 3D"}).getByRole("button",{name:"Acabado"}).click();
  await expect(canvas).toHaveAttribute("data-mode","finished");
  await expect(canvas).toHaveAttribute("data-context-loaded","true",{timeout:20000});
  await expect(page.getByText("JPN · PRÉ-PROJETO VISUAL · NÃO DIMENSIONADO")).toBeVisible();
  await expect(page.getByLabel("Cotas do pré-projeto")).toContainText("Vão 10 m");
  await expect(page.getByLabel("Cotas do pré-projeto")).toContainText("Comprimento 20 m");
  await page.getByLabel("Tipo de telha").selectOption("sandwich");
  await page.getByLabel("Cor do telhado").selectOption("terracotta");
  await page.getByLabel("Paredes").selectOption("three");
  await page.getByLabel(/Opacidade do telhado/).focus();
  await page.getByLabel(/Opacidade do telhado/).press("ArrowLeft");
  await expect(page.getByLabel(/Opacidade do telhado/)).toHaveValue("0.95");
  await page.getByLabel("Pessoa (1,70 m)").uncheck();
  await expect(page.getByLabel("Pessoa (1,70 m)")).not.toBeChecked();
  await expect(canvas).toHaveAttribute("data-mode","finished");
  const drawCalls=Number(await canvas.getAttribute("data-draw-calls"));
  expect(drawCalls).toBeGreaterThan(0);
  expect(drawCalls).toBeLessThan(200);
  const downloadPromise=page.waitForEvent("download");
  await page.getByRole("button",{name:"Salvar imagem PNG"}).click();
  const download=await downloadPromise;
  expect(download.suggestedFilename()).toBe("jpn-apresentacao-preliminar.png");
  await page.getByRole("group",{name:"Modo de visualização 3D"}).getByRole("button",{name:"Perfis 3D"}).click();
  await expect(canvas).toHaveAttribute("data-mode","profiles");
  await page.getByRole("group",{name:"Modo de visualização 3D"}).getByRole("button",{name:"Estrutural"}).click();
  await expect(canvas).toHaveAttribute("data-mode","structural");
  await page.getByRole("group",{name:"Modo de visualização 3D"}).getByRole("button",{name:"Misto"}).click();
  await expect(canvas).toHaveAttribute("data-mode","mixed");
  await expect(page.getByTestId("takeoff-totals")).toHaveText(before);
  expect(await page.evaluate(()=>JSON.stringify(JSON.parse(localStorage.getItem("jpn-projetos:v1")!).projects.at(-1).planning))).toBe(previous);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
test("a cobertura de uma água também ativa o Acabado sem mudar os quantitativos",async({page})=>{
  await page.goto("/projetos/novo");
  await page.getByLabel("Formato da cobertura").selectOption("mono");
  await page.getByLabel("Largura (m)").fill("8");
  await page.getByLabel("Comprimento (m)").fill("12");
  await page.getByLabel("Altura (m)").fill("3");
  await page.getByRole("button",{name:"Gerar modelo 3D"}).click();
  const canvas=page.getByRole("img",{name:"Modelo 3D da estrutura"});
  await page.getByRole("group",{name:"Modo de visualização 3D"}).getByRole("button",{name:"Acabado"}).click();
  await expect(canvas).toHaveAttribute("data-context-loaded","true");
  await expect(page.getByLabel("Cotas do pré-projeto")).toContainText("Vão 8 m");
  await expect(page.getByLabel("Cotas do pré-projeto")).toContainText("Comprimento 12 m");
});
