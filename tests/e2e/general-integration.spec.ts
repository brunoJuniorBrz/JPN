import {expect,test} from "@playwright/test";
import {mkdir,readFile,writeFile} from "node:fs/promises";
import {generalIntegrationProject} from "../../src/domain/test-support/general-integration-project";
import {mixedInputHash} from "../../src/domain/mixed-analysis";
import {openResultTab} from "./result-tabs";

for(const width of [390,1440])test(`integração geral: obra/superfície/apoios/ações -> HTTP/Python -> relatório em ${width}px`,async({page})=>{
  test.setTimeout(120000); // Existing full-journey budget; worker stays at 20 s.
  await page.setViewportSize({width,height:950});
  const errors:string[]=[];page.on("pageerror",error=>errors.push(error.message));
  const input=generalIntegrationProject();input.name+=` ${width}px`;
  await page.goto("/projetos/novo");
  await page.getByText("Importar modelo estrutural declarado",{exact:true}).click();
  await page.getByLabel("Importar modelo estrutural JSON").setInputFiles({name:"cobertura-fisica.json",mimeType:"application/json",buffer:Buffer.from(JSON.stringify(input))});
  await expect(page).toHaveURL(/fluxo=levantamento/);
  const ownerId=new URL(page.url()).pathname.split("/").at(-1)!;
  await openResultTab(page,"Engenharia");
  let panel=page.getByTestId("mixed-workspace");
  await panel.getByRole("button",{name:"Preparação mista",exact:true}).click();
  await panel.getByRole("button",{name:"3. Cargas e combinações"}).click();
  const roof=panel.getByTestId("physical-roof-workflow");
  await roof.getByText("Cadastrar novo pano físico",{exact:true}).click();
  await roof.getByLabel("ID do pano físico").fill("ROOF");
  await roof.getByLabel("Fonte do levantamento XYZ").fill("Levantamento sintético explícito de 4 x 5 m");
  await roof.getByLabel("Revisão do pano físico").fill("ROOF-1");
  await roof.getByLabel(/Vértices externos em mm/).fill("0;0;3000\n4000;0;3400\n4000;5000;3400\n0;5000;3000");
  for(const id of ["P1A","P1B","P2A","P2B"]){
    await roof.getByLabel("Terça existente para associar ao pano").selectOption(id);
    await roof.getByRole("button",{name:"Associar terça"}).click();
  }
  await roof.getByRole("button",{name:"Salvar pano físico"}).click();
  await roof.getByText("Registrar ação de área",{exact:true}).click();
  await roof.getByLabel("Caso físico da ação").selectOption("AREA");
  await roof.getByLabel("Intensidade da pressão (kN/m²)").fill("0,2");
  await roof.getByLabel("Origem da ação").fill("Pressão de referência analítica, sem fator normativo");
  await roof.getByLabel("Revisão da ação").fill("LOAD-1");
  await roof.getByLabel("Hipótese declarada de transmissão da telha à terça").fill("Telha simplesmente apoiada entre as duas linhas físicas de terças");
  await roof.getByRole("button",{name:"Salvar ação de área"}).click();
  await roof.getByRole("button",{name:"Conferir distribuição física das cargas"}).click();
  await expect(roof.getByText(/Distribuição física conferida para 1 ação/)).toBeVisible();
  await expect(panel.getByLabel("Fator AREA em ELASTIC",{exact:true})).toHaveValue("1");
  await panel.getByText("Conectividade física e segmentação",{exact:true}).click();
  await panel.getByLabel("Fonte da revisão de conectividade").fill("Revisão explícita das seis barras e seis nós deste ensaio");
  await panel.getByRole("checkbox",{name:/Revisei todas as juntas listadas/}).check();
  await panel.getByRole("button",{name:"Registrar conectividade revisada",exact:true}).click();
  await page.getByRole("button",{name:"Salvar levantamento",exact:true}).click();
  await page.reload();await openResultTab(page,"Engenharia");panel=page.getByTestId("mixed-workspace");
  await expect(panel.getByTestId("mixed-scope")).toContainText("OBRA ATUAL");
  await expect(panel.getByTestId("mixed-health")).toContainText("PyNiteFEA 3.2.1",{timeout:25000});
  const saved=await page.evaluate(id=>JSON.parse(localStorage.getItem("jpn-projetos:v1")!).projects.find((p:{id:string})=>p.id===id),ownerId);
  expect(saved.workspace.physicalStructure.nodes).toEqual(input.workspace.physicalStructure!.nodes);
  expect(saved.workspace.spatialPreparation.supportInterfaces).toHaveLength(4);
  expect(saved.workspace.spatialPreparation.physicalRoofFaces.faces[0].id).toBe("ROOF");
  const response=page.waitForResponse(r=>r.url().endsWith("/api/experimental/mixed3d")&&r.request().method()==="POST");
  await panel.getByRole("button",{name:"Executar análise mista local",exact:true}).click();
  const http=await response;expect(http.status()).toBe(200);
  const request=http.request().postDataJSON(),out=await http.json(),result=out.result;
  expect(request.project.id).toBe(ownerId);expect(request.schema_version).toBe("jpn.mixed3d/2");
  expect(request.nodes).toHaveLength(6);expect(request.members).toHaveLength(6);expect(request.supports).toHaveLength(4);
  expect(request.nodal_loads).toHaveLength(0);expect(request.member_loads).toHaveLength(4);
  expect(result.input_sha256).toBe(await mixedInputHash(request));
  const combo=result.combinations.ELASTIC;
  const expected=-400*5**4/(384*200e9*1e-6);
  expect(combo.nodes.AM.translation_m[2]).toBeCloseTo(expected,10);
  expect(combo.nodes.BM.translation_m[2]).toBeCloseTo(expected,10);
  const rz=Object.values(combo.nodes).reduce<number>((s,n)=>s+(n as {reaction_force_n:number[]}).reaction_force_n[2],0);
  expect(rz).toBeCloseTo(4000,5);expect(combo.equilibrium.relative_residual).toBeLessThan(1e-8);
  await expect(panel.getByTestId("mixed-result-state")).toContainText("Resultado calculado");
  const reportPanel=panel.getByTestId("resistance-report");await expect(reportPanel).toBeVisible();
  const downloading=page.waitForEvent("download");
  await reportPanel.getByRole("button",{name:"Exportar relatório resistente preliminar",exact:true}).click();
  const file=await downloading,report=JSON.parse(await readFile((await file.path())!,"utf8"));
  expect(report.approvedForFabrication).toBe(false);expect(report.releaseGate.status).toBe("NOT_READY_BLOCKED");
  expect(report.binding.inputSha256).toBe(result.input_sha256);
  await panel.getByRole("button",{name:"Preparação mista",exact:true}).click();
  await panel.getByLabel("Seção física cadastrada",{exact:true}).selectOption("S1");
  await panel.getByLabel("Seção S1 · Inércia Iy (cm⁴)",{exact:true}).fill("200");
  await panel.getByLabel("Seção S1 · revisão",{exact:true}).fill("2");
  await expect(panel.getByTestId("mixed-stale")).toBeVisible();
  const response2=page.waitForResponse(r=>r.url().endsWith("/api/experimental/mixed3d")&&r.request().method()==="POST");
  await panel.getByRole("button",{name:"Executar análise mista local",exact:true}).click();
  const out2=await(await response2).json();
  expect(out2.result.input_sha256).not.toBe(result.input_sha256);
  expect(out2.result.combinations.ELASTIC.nodes.AM.translation_m[2]).toBeCloseTo(expected/2,10);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(errors).toEqual([]);
  await mkdir(".tools/integration-general-runtime",{recursive:true});
  await writeFile(`.tools/integration-general-runtime/journey-${width}.json`,JSON.stringify({width,request,result,report,recalculated:out2.result},null,2));
  await page.screenshot({path:`.tools/integration-general-runtime/journey-${width}.png`,fullPage:true});
});
